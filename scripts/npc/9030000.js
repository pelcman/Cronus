// プレドリック — 雇用商人の回収サービス
function start() {
    if (!player.hasMerchant()) {
        cm.sendOk("私は雇用商人を管理しているプレドリックです。\r\n"
            + "あなたの商店は今、営業していないようですね。雇用商人を開いたら、"
            + "遠くからでも私が店じまいと売上金の回収を承りますよ。");
        return;
    }
    if (cm.askYesNo("あなたの雇用商人が営業中です。店をたたんで、残った商品と売上金を回収しますか?")) {
        if (player.retrieveMerchant()) {
            cm.sendOk("回収が完了しました。持ち物と所持金をご確認ください。ご利用ありがとうございました。");
        } else {
            cm.sendOk("おや……すでに店じまいしていたようです。");
        }
    }
}
