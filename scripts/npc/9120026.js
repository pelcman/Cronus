// クリスタル (ネオシティ/未来トウキョウの時空移動装置。wz info/script = "tell_Tokyo")
// カムナ(802000101)と公園2095(802000313)に立っており、各時代のハブへ渡す。
// 本来はクエスト進行に応じて行ける時代が増える演出だが、その進行データはリファレンス
// にも存在しないため、行き先メニューは常時開放している(クエスト自体の受注・討伐・
// 納品条件はクエストデータ側で通常どおり効く)。
var ERAS = [
    ["カムナ (現代)",          802000101],
    ["忘却の森 (入口)",        802000100],
    ["お台場 2100年",         802000200],
    ["公園 2095年",           802000300],
    ["秋葉原 2102年",         802000400],
    ["渋谷 2102年",           802000700],
    ["六本木モール 2102年",     802000800]
];
function start() {
    var here = player.getMapId();
    var menu = "クリスタルが淡く光っている。時空を超えて、どの時代へ向かいますか?";
    for (var i = 0; i < ERAS.length; i++) {
        menu += "\r\n#L" + i + "#" + ERAS[i][0] + (ERAS[i][1] == here ? " (現在地)" : "") + "#l";
    }
    var pick = cm.askMenu(menu);
    if (pick < 0 || pick >= ERAS.length) {
        return;
    }
    if (ERAS[pick][1] == here) {
        cm.sendOk("……今いる時代だ。クリスタルは静かに光を落とした。");
        return;
    }
    player.warp(ERAS[pick][1]);
}
