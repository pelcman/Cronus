// 鉱石・宝石の精錬 (refine_* 系NPC共通)。オラクルにレシピが無いため簡易仕様:
// 原料10個 + 手数料 → 精錬品1個 (板500メル・宝石1000メル)。ID対は実データ検証済み。
var ORES = [
    [4010000, 4011000, "青銅",        500],
    [4010001, 4011001, "鋼鉄",        500],
    [4010002, 4011002, "ミスリル",     500],
    [4010003, 4011003, "アダマンティウム", 500],
    [4010004, 4011004, "銀",          500],
    [4010005, 4011005, "オリハルコン",  500],
    [4010006, 4011006, "金",          500],
    [4010007, 4011008, "リチウム",     500]
];
var GEMS = [
    [4020000, 4021000, "ガーネット",   1000],
    [4020001, 4021001, "紫水晶",      1000],
    [4020002, 4021002, "アクアマリン", 1000],
    [4020003, 4021003, "エメラルド",   1000],
    [4020004, 4021004, "オパール",     1000],
    [4020005, 4021005, "サファイア",   1000],
    [4020006, 4021006, "トパーズ",     1000],
    [4020007, 4021007, "ダイヤモンド", 1000],
    [4020008, 4021008, "黒水晶",      1000]
];
var NEED = 10;
function refineMenu(list, kind) {
    var menu = kind + "の精錬だね。原料" + NEED + "個と手数料で1個に精錬するよ。どれにする?";
    for (var i = 0; i < list.length; i++) {
        menu += "\r\n#L" + i + "#" + list[i][2] + " (" + list[i][3] + "メル)#l";
    }
    var pick = cm.askMenu(menu);
    if (pick < 0 || pick >= list.length) return;
    var t = list[pick];
    if (player.itemQuantity(t[0]) < NEED) {
        cm.sendOk("#b#t" + t[0] + "##kが" + NEED + "個必要だよ。まだ足りないみたいだね。");
        return;
    }
    if (player.getMeso() < t[3]) {
        cm.sendOk("手数料の" + t[3] + "メルが足りないよ。");
        return;
    }
    player.gainItem(t[0], -NEED);
    player.gainMeso(-t[3]);
    player.gainItem(t[1], 1);
    cm.sendOk("できたよ!#b#t" + t[1] + "##k #i" + t[1] + "#\r\nまた原料が集まったらおいで。");
}
function start() {
    var pick = cm.askMenu("やあ、精錬の依頼かい?"
        + "\r\n#L0#鉱石を精錬する#l"
        + "\r\n#L1#宝石の原石を加工する#l");
    if (pick == 0) refineMenu(ORES, "鉱石");
    else if (pick == 1) refineMenu(GEMS, "宝石");
}
