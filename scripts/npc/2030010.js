// ザクムの祭壇 — ザクム召喚 (簡略版: 供物なしで召喚できる)
// 本体 8800000 は倒すと 8800001 → 8800002 と姿を変える(wz の revive 連鎖)。腕は 8800003〜8800010。
function start() {
    if (player.mobCount() > 0) {
        cm.sendOk("祭壇はまだ静まっていない……今の戦いが終わるまで待つのだ。");
        return;
    }
    if (!cm.askYesNo("祭壇に手をかざせば、火と岩の魔神ザクムが目覚める。"
            + "全滅しても文句は言えんぞ。……召喚するか?")) {
        cm.sendOk("賢明な判断かもしれんな。");
        return;
    }
    player.spawnMob(8800000, 1); // 本体 (第1形態)
    for (var arm = 8800003; arm <= 8800010; arm++) {
        player.spawnMob(arm, 1);
    }
    cm.sendOk("大地が震える……ザクムが目覚めた!腕を全て砕き、本体を討て!");
}
