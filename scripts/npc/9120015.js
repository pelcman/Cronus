function start() {
    var pick = cm.askMenu("俺に何の用だ？\r\n#L0##bアジトの情報を集める#l\r\n#L1#アジトへ連れて行ってくれ#l\r\n#L2#何でもない#l#k");
    if (pick == 0) {
        cm.sendOk("アジトまで連れて行ってやれるが、あそこは喧嘩っ早いチンピラだらけだ。入るには相当な強さと度胸が要る。アジトの奥には、この辺りのボスどもを束ねる大ボスがいる。アジトまで行くのは簡単だが、最上階のボスの部屋には #b一日に一度#k しか入れない。ボスの部屋は遊び半分で入る所じゃない。長居はせず、手早く片付けることだ。ボス本人も手強いが、たどり着くまでにも恐ろしく強い連中が待ち構えているぞ。楽じゃない。");
        return;
    }
    if (pick == 1) {
        cm.sendNext("おお、勇ましいやつだ。お前が来るのを待っていた。あのチンピラどもを放っておいたら、この辺りがどうなるか分からない。その前に、やつらを片付けて 5 階にいるボスを倒してくれ。ボスは賢者でも手を焼くほど強い。だがお前の目を見れば分かる。虎の目だ。やれるって目だ。さあ行こう！");
        player.warpPortal(801040000, "in00");
        return;
    }
    cm.sendOk("俺は忙しいんだ！　用がないなら放っといてくれ！");
}
