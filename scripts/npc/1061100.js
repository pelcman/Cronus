function start() {
    cm.sendNext("いらっしゃいませ。スリーピーホテルへようこそ。当ホテルは、いつでも最高のおもてなしを心がけております。狩りでお疲れでしたら、ごゆっくりお休みになりませんか？");
    var pick = cm.askMenu("お部屋は 2 種類ご用意しております。お好きな方をお選びください。\r\n#b#L0#一般サウナ (1 回 499 メソ)#l\r\n#L1#高級サウナ (1 回 999 メソ)#l");
    if (pick != 0 && pick != 1) {
        return;
    }
    var cost = pick == 0 ? 499 : 999;
    var text = pick == 0
        ? "一般サウナをお選びですね。HP と MP が早く回復し、中でアイテムも買えます。お入りになりますか？"
        : "高級サウナをお選びですね。一般サウナよりさらに早く HP と MP が回復し、特別な品も見つかるかもしれません。お入りになりますか？";
    if (!cm.askYesNo(text)) {
        cm.sendOk("ほかのサービスもございますので、ゆっくりお考えになってお決めください。");
        return;
    }
    if (player.getMeso() < cost) {
        cm.sendOk("申し訳ございません。メソが足りないようです。ご利用には " + cost + " メソ必要です。");
        return;
    }
    player.gainMeso(-cost);
    player.warp(pick == 0 ? 105040401 : 105040402, 0);
}
