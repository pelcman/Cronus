// 表示板 — ルディブリアム・パーティークエスト「玩具工場の異変」入場 (簡略版)
function start() {
    var pick = cm.askMenu("『挑戦者求む!エオス塔の異変を解決してくれた方には豪華な報酬を差し上げます』"
        + "\r\n#L0#挑戦する (ステージ1へ入場)#l"
        + "\r\n#L1#詳しく読む#l");
    if (pick == 1) {
        cm.sendOk("中では各ステージのバルーンに話しかけて先へ進みます。"
            + "戦闘ステージではモンスターが通行証を落とします。"
            + "途中で帰りたくなったらアンダソンくんに話しかけてください。");
        return;
    }
    if (cm.askYesNo("仲間と一緒に入るなら、全員がこの表示板を調べてください。入場しますか?")) {
        player.warp(922010100);
    }
}
