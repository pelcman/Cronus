// シャンクス 22000 (サウスペリ 2000000) — メイプルアイランドからビクトリアアイランド(港口 104000000)へ渡す船長。150 メソ、Lv7 以上。
// ルーカスの推薦書(4031801)があれば無料で推薦書を回収。出典 Reference/Cosmic/scripts/npc/22000.js。台詞は創作。
function start() {
    if (!cm.askYesNo("この船に乗れば、もっと大きな大陸へ行ける。#e150 メソ#n で #bビクトリアアイランド#k まで送ってやろう。ただし、一度この島を出たら二度と戻れないぞ。どうする、ビクトリアアイランドへ行くか？")) {
        cm.sendOk("ふむ…まだこの島でやることがあるようだな。");
        return;
    }
    if (player.haveItem(4031801)) {
        cm.sendNext("よし、では 150 メソを…おや、それは何だ？　アムホストの村長ルーカスの推薦書か！　早く言ってくれよ。このシャンクス、見どころのあるやつは見逃さない。ルーカスの推薦があるなら、お前は冒険者として大した素質があるってことだ。金なんて取れるか！");
        cm.sendNext("推薦書があるなら料金は要らない。さあ、しっかりつかまれ。これからビクトリアアイランドへ向かう。少し揺れるぞ！");
        player.gainItem(4031801, -1);
        player.warp(104000000, 0);
        return;
    }
    cm.sendNext("この島に飽きたのか？　ほら…まずは #e150 メソ#n をよこしな。");
    if (player.getLevel() < 7) {
        cm.sendOk("うーん…まだ力が足りないな。ビクトリアアイランドへ行くには、少なくとも #bレベル 7#k は必要だ。");
        return;
    }
    if (player.getMeso() < 150) {
        cm.sendOk("なに？　金も持たずに行くつもりだったのか？　変わったやつだな…。");
        return;
    }
    cm.sendNext("よし！　#e150#n メソ、確かに受け取った！　さあ、ビクトリアアイランドへ出発だ！");
    player.gainMeso(-150);
    player.warp(104000000, 0);
}
