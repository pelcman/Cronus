// ごみ箱おじさん (JMS) — ごみ箱をあさらせてもらう。たまに拾い物が出る小ネタNPC。
// 本家の正確な挙動のオラクルが無いため、フレーバー+低確率のジャンク品として実装。
var JUNK = [
    [4000000, "カタツムリの殻"],   // 汎用ドロップ素材
    [4000003, "青いキノコの傘"],
    [2000000, "赤いポーション"]
];
function start() {
    var pick = cm.askMenu("よう、あんた。このごみ箱に用かい?"
        + "\r\n#L0#ごみ箱をあさってみる#l"
        + "\r\n#L1#……何でもないです#l");
    if (pick != 0) {
        cm.sendOk("だろうな。ごみ箱に用がある奴なんてそういないさ。");
        return;
    }
    // 3回に1回くらい何か見つかる。残りは空振り。
    if (Math.random() < 0.33) {
        var t = JUNK[Math.floor(Math.random() * JUNK.length)];
        player.gainItem(t[0], 1);
        cm.sendOk("お、何か出てきたぞ。#b" + t[1] + "#k……いるなら持ってきな。");
    } else {
        cm.sendOk("残念、今日は空っぽだ。まあ、ごみ箱だからな。");
    }
}
