// 精錬屋 — 鉱石・原石の精錬 (原料4つ + 手数料 → 精錬品1つ)
function start() {
    var minerals = [
        [4010000, "青銅", 4011000, 300],
        [4010001, "鋼鉄", 4011001, 400],
        [4010002, "ミスリル", 4011002, 500],
        [4010003, "アダマンティウム", 4011003, 600],
        [4010004, "銀", 4011004, 700],
        [4010005, "オリハルコン", 4011005, 800],
        [4010006, "金", 4011006, 1000]
    ];
    var jewels = [
        [4020000, "ガーネット", 4021000, 500],
        [4020001, "紫水晶", 4021001, 500],
        [4020002, "アクアマリン", 4021002, 500],
        [4020003, "エメラルド", 4021003, 500],
        [4020004, "オパール", 4021004, 500],
        [4020005, "サファイア", 4021005, 500],
        [4020006, "トパーズ", 4021006, 500],
        [4020007, "ダイヤモンド", 4021007, 1000],
        [4020008, "黒水晶", 4021008, 1000]
    ];
    var kind = cm.askMenu("私は精錬職人だ。何を精錬してほしいんだ?\r\n#L0#鉱物を精錬する#l\r\n#L1#原石を精錬する#l");
    var table = (kind == 0) ? minerals : jewels;
    var label = (kind == 0) ? "の原料" : "の原石";
    var menu = "どれを精錬する?同じ" + ((kind == 0) ? "原料" : "原石") + "が4つ必要だ。";
    for (var i = 0; i < table.length; i++) {
        menu += "\r\n#L" + i + "#" + table[i][1] + " (手数料" + table[i][3] + "メル)#l";
    }
    var pick = cm.askMenu(menu);
    var t = table[pick];
    if (player.itemQuantity(t[0]) < 4) {
        cm.sendOk(t[1] + label + "が足りないな。4つ持ってきてくれ。");
        return;
    }
    if (player.getMeso() < t[3]) {
        cm.sendOk("手数料の" + t[3] + "メルが足りないようだ。");
        return;
    }
    player.gainItem(t[0], -4);
    player.gainMeso(-t[3]);
    player.gainItem(t[2], 1);
    cm.sendOk("ほら、できたぞ。見事な" + t[1] + "だ。また原料が集まったら持ってきな。");
}
