// 本来の機能(ペット訓練)のオラクルが無いため案内役として実装。
function start() {
    var pick = cm.askMenu("ペットのことなら私に聞いて!"
        + "\r\n#L0#ペットってどうやって連れて歩くの?#l"
        + "\r\n#L1#親密度って何?#l"
        + "\r\n#L2#ペットフードはどこで買えるの?#l");
    if (pick == 0) {
        cm.sendOk("ペットはキャッシュインベントリの#bペットをダブルクリック#kすると召喚できるよ。"
            + "\r\nもう一度ダブルクリックするとお家に帰るからね。");
    } else if (pick == 1) {
        cm.sendOk("親密度はペットとの仲良し度。#bエサをあげる#kと少しずつ上がっていくよ。"
            + "\r\n仲良くなるとレベルが上がって、名前の色も変わるんだ。");
    } else if (pick == 2) {
        cm.sendOk("#bペットフード(2120000)#kは雑貨店で売ってることが多いよ。"
            + "\r\n持っていれば、おなかを空かせたペットにあげられるからね。");
    }
}
