// 本来のプール定義(BMS Server.wz/Gachapon.img)はリファレンスにも存在しないため、
// スクロール・イス・装備・消費の混合プールを独自に構成している(全IDは実データ検証済み)。
var TICKET = 5220000;
var PRICE = 10000;
var POOL = [2040002,2040402,2040502,2040602,2040702,2040802,2040902,2041002,2041016,2041020,2043002,2043102,2043202,2043302,2043702,2043802,2044002,2044102,2044202,2044302,2044402,2044502,2044602,2044702,2040301,2040305,3010000,3010001,3010002,3010003,3010004,3010005,3010006,3010007,3010008,3010009,3010010,3010011,1002357,1002391,1002392,1082149,1082150,1052095,1072238,1102040,1102041,1032023,1032024,1092045,1302056,1302059,1312032,1322054,1332049,1372034,1382039,1402039,1412027,1422029,1432038,1442046,1452045,1462040,1472053,1482013,1492013,2000004,2000005,2020012,2020013,2022003,2012002,2050004,4003000,4006000,4006001,2340000];
function start() {
    var haveTicket = player.haveItem(TICKET);
    var cost = haveTicket ? "ガシャポンチケット1枚" : PRICE + "メル";
    var pick = cm.askMenu("ガシャポンへようこそ!何が出るかはお楽しみ。"
        + "\r\n#L0#回す (" + cost + ")#l"
        + "\r\n#L1#やめておく#l");
    if (pick != 0) {
        cm.sendOk("また回したくなったら来てね。");
        return;
    }
    if (haveTicket) {
        player.gainItem(TICKET, -1);
    } else if (player.getMeso() >= PRICE) {
        player.gainMeso(-PRICE);
    } else {
        cm.sendOk("チケットもメルも足りないみたい。#b" + PRICE + "メル#kかガシャポンチケットを持ってきてね。");
        return;
    }
    var prize = POOL[Math.floor(Math.random() * POOL.length)];
    player.gainItem(prize, 1);
    cm.sendOk("おめでとう!#b#t" + prize + "##kが出たよ!\r\n#i" + prize + "#");
}
