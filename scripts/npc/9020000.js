// (簡略版: パーティー人数チェックなし。誰でも入場でき、各ステージは各自クリアで進む)
function start() {
    var pick = cm.askMenu("君たち、力を試したくはないか?「一つ目の同行」への挑戦者を探しているんだ。"
        + "\r\n#L0#挑戦する (ステージ1へ入場)#l"
        + "\r\n#L1#詳しく聞く#l");
    if (pick == 1) {
        cm.sendOk("中では仲間と協力してステージを進むんだ。"
            + "ステージ1ではリゲーターを倒してクーポンを20枚集めること。"
            + "各ステージのクロートに話しかければ先へ進める。途中で帰りたくなったらネーラに話すといい。");
        return;
    }
    if (cm.askYesNo("準備はいいか?仲間と一緒に入るなら、全員がわしに話しかけるんだぞ。")) {
        player.warp(103000800);
    }
}
