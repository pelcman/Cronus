// メガネを探して！ (quest 2186, NPC 1094001 アベル, ノーチラス) — アベルのメガネ(4031853)を届けると完了。JMS: 終了スクリプト q2186e、
// Check[1] は 4031853×1、Act は空なので報酬(EXP 1700、帰還の書（ノーチラス）2030019×10 = Cosmic の値)はスクリプト側。
// Cosmic にある「誰かのメガネ(4031854/4031855)」の別ルートは JMS の完了条件(4031853 所持)では起きないので省く。台詞は創作。
function end() {
    if (!player.haveItem(4031853)) {
        qm.sendOk("私のメガネ、まだ見つからないのかい？　この船のどこかに落としたはずなんだが…");
        return;
    }
    player.gainItem(4031853, -1);
    player.gainExp(1700);
    player.gainItem(2030019, 10);
    qm.sendOk("おお、私のメガネだ！　ありがとう、本当にありがとう。これでやっと仕事に戻れる。お礼にこれを持っていってくれ。");
    player.completeQuest(2186);
}
