// マレンの実技の授業 (quest 6032, NPC 2110004 マレン) — メイカーの実技講義を聞いて受講料 10,000 メソを払う。受講料は JMS の
// Act[1](money -10000)がデータ経路で引く。出典 Reference/Cosmic/scripts/quest/6032.js。JMS: 終了スクリプト q6032e。台詞は創作。
function end() {
    if (player.getMeso() < 10000) {
        qm.sendOk("実技の授業は受講料 #b10,000 メソ#k だ。用意してから来なさい。");
        return;
    }
    qm.sendNext("私の授業を受けに来たのか。よし、手短にいこう。");
    qm.sendNext("#bメイカー#k の実際の使い方を教える。スキルを使うと作れる物の一覧が出る。材料と手数料をそろえて作るだけだ。");
    qm.sendNext("たとえば #bウェイトイヤリング#k を作るなら、必要な鉱物とモンスター結晶、それに手数料。材料が足りなければ作れない。");
    qm.sendNext("さて、講義代として 10,000 メソをもらおう。実技はこれで終わりだ。");
    player.completeQuest(6032);
}
