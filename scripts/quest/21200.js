// 主を待つ武器 (quest 21200, 受注 NPC 1201000 リリン → 完了 NPC 1201002 マッハ, Lv30) — リエンの巨大な鉾の様子がおかしいと聞き、鉾(マッハ)と初めて言葉を
// 交わす。完了時に隠し記録 21203 を "0" にする(JMS の 21202 の受注条件 infoNumber=21203 infoex=0)。
// 出典 Reference/Cosmic/scripts/quest/21200.js。JMS: 開始 q21200s / 終了 q21200e、normalAutoStart、Act は空。台詞は創作。
function start() {
    if (!qm.askAccept("修行は順調ですか？　おや、もうそんなレベルに…。ところで、#b#m140000000##k の #b#p1201001##k の様子が最近おかしいのです。見てきてくれますか？")) {
        qm.sendOk("よく考えてから決めてくださいね。決心がついたら、また来てください。");
        return;
    }
    qm.sendOk("#p1201001# が、まるで誰かを呼ぶように震えているのです。あなたなら、何か分かるかもしれません。");
    player.startQuest(21200);
}

function end() {
    qm.sendNext("ブーン、ブーン、ブーン……");
    qm.sendNext("（#p1201001# がうねるような響きを立てている。でも、誰が…？）");
    qm.sendNext("（見たことのない誰かの声だ。人間には見えない…。）");
    qm.sendNext("おい、アラン！　聞こえないのか？　聞こえないのかと言っている！　まったく…");
    qm.sendNext("（ん？　今の声は誰だ？　怒った少年みたいな声だが…）");
    qm.sendNext("ああ、俺のたった一人の主が、何百年も氷の中に閉じ込められるなんて…");
    qm.sendNext("（お前は…誰だ？）");
    qm.sendNext("アラン？　今度は聞こえたか？　俺だよ！　分からないのか？　お前の鉾、#p1201002# だ！");
    qm.sendNext("（…#p1201002#？　#p1201001# がしゃべるのか？）");
    qm.sendNext("なんだその疑わしそうな顔は。記憶を失っているのは知っているが、俺のことまで忘れたのか？");
    qm.sendNext("（すまない、本当に何も覚えていないんだ。）");
    if (!qm.askYesNo("すまないで済むか！　俺がどれだけ寂しくて退屈だったか分かるか？　…まあいい。とにかく、これからは一緒だ。いいな？")) {
        qm.sendOk("おい！　せめて「頑張る」くらい言え！");
        return;
    }
    player.completeQuest(21200);
    player.setQuestData(21203, "0");
    qm.sendOk("（#p1201002# を名乗るこの声は、どうやら本当に鉾の声らしい…。）");
}
