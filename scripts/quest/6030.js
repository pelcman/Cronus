// カソンの錬金術の授業 (quest 6030, 受注 2110004 マレン → 完了 NPC 2111000 カソン) — 錬金術の基礎講義を聞いて受講料 10,000 メソを払う。
// 受講料は JMS の Act[1](money -10000)がデータ経路で引くので、スクリプトは残高だけ確かめる。出典 Reference/Cosmic/scripts/quest/6030.js。
// JMS: 終了スクリプト q6030e。台詞は創作(講義の趣旨は Cosmic どおり)。
function end() {
    if (player.getMeso() < 10000) {
        qm.sendOk("授業を受けるなら、まず受講料の #b10,000 メソ#k を用意してきなさい。");
        return;
    }
    qm.sendNext("では、錬金術の基礎について教えよう。");
    qm.sendNext("科学が物事を分解して考えるのに対し、錬金術は「ばらばらの物を一つにまとめる」術だ。物質に語りかけ、望む形へ導く。");
    qm.sendNext("ばらばらの部品に「全体になれ」と告げるのは、科学では難しい。錬金術ならそれができる。素早く、そして清潔にね。");
    qm.sendNext("覚えておきなさい。#bメイカー#k の要は「交換」だ。材料と結果は釣り合っていなければならない。それが錬金術の掟だ。");
    qm.sendOk("これで基礎講義はおしまいだ。受講料はいただいておくよ。");
    player.completeQuest(6030);
}
