function start() {
    qm.sendNext("もう分かっているだろうが、私がドランだ。かつては協会でも名の知れた錬金術師だった…今はこの通り、隠れて暮らしているがね。");
    qm.sendNext("私の作ったヒューマノイドは、本来は家事や研究、そして人々の暮らしを助けるためのものだった。だが、ある実験の失敗で制御を失ってしまった。");
    if (!qm.askAccept("それでも、今ここで止まるわけにはいかない。私の創造物はまだ研究所を徘徊し、破壊をもたらしている。手を貸してくれるか？")) {
        qm.sendOk("…そうか。気が変わったら、また来てくれ。");
        return;
    }
    qm.sendNext("理解してくれて感謝する。私の居場所を知っているということは、ファウェンに会ったのだろう。彼には助けられている。");
    qm.sendNext("それと、個人的な頼みがある。妻のことが心配なのだ。私の家に、妻へ渡したいペンダントを隠してある。");
    qm.sendNext("#rこの模様をよく覚えておいてくれ！#k ペンダントは私の家の、#b特定の順番で調べた入れ物#k の中に隠してある。ファウェンに話せば、詳しいことが分かるはずだ。");
    player.startQuest(3321);
}
