function end() {
    qm.sendNext("まず、暗黒の魔法使いを倒して俺を有名にすると約束しろ。");
    qm.sendNext("（俺が約束したら、#p1203000# に鉾を作ってもらえる…そういう話だったな。）");
    qm.sendNext("あれだけ頼み込んだんだ、もう少し丁寧に扱ってくれてもいいだろう？");
    qm.sendNext("（頼み込んだ覚えはないが…。）");
    qm.sendNext("なに？　頼んでない？　はっ！　#p1203000# は、お前が泣いて頼んだと言っていたぞ。");
    qm.sendNext("（…ちょっとだけ、かもしれない。）");
    qm.sendNext("アラン、やっぱりお前だ！　ぐすっ…いや、待て、感傷的になどなっていないぞ。");
    if (!qm.askAccept("記憶を失っていても、お前は今も俺の主だ。さあ、俺を手に取れ。失った力を、少しずつ取り戻すんだ。")) {
        qm.sendOk("おい！　せめて「頑張る」くらい言え！");
        return;
    }
    if (player.getJob() != 2100) {
        qm.sendOk("（マッハはもう、この手に馴染んでいる。）");
        return;
    }
    player.changeJob(2110);
    player.completeQuest(21201);
    qm.sendOk("昔の全盛期には遠く及ばないが、これで少しは英雄らしくなった。修行を続けて、俺の力を全部引き出せるようになれ。");
}
