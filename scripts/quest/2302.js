// キノコ王国の事件！ (quest 2302, 受注 NPC 1052001 ダークロード → 完了 NPC 1300005 警護大将) — 盗賊系(410〜434) の Lv30〜38 が対象。転職官が
// 転職官の推薦書(4032375)を渡してキノコ城 106020000 へ送り、警護大将が推薦書を受け取って 勇者の試験(2312) を始める。
// 出典 Reference/Cosmic/scripts/quest/2302.js (2300〜2310 は NPC 違いの同内容)。JMS: q2302s / q2302e、Act は両側とも空なので
// 推薦書の付与と回収・EXP 6000(Cosmic の値)・2312 の開始はスクリプト側で行う。台詞は創作。
function start() {
    if (!qm.askAccept("転職を済ませたお前なら、もう任せられそうだな。実は頼みたいことがある。話を聞いてくれるか？")) {
        qm.sendOk("そうか…急ぎの用なのだが。時間ができたら、また声をかけてくれ。");
        return;
    }
    qm.sendNext("実は今、#bキノコ王国#k が大変なことになっているらしい。");
    qm.sendNext("詳しいことは分からないが、何かとんでもないことが起きているのは確かだ。王国からの使いが助けを求めてきている。お前に行ってもらいたい。");
    var knows = qm.askYesNo("ところで、キノコ王国の場所は知っているか？　知らなければ道順を教えるし、知っているなら今すぐ送ってやろう。この #b転職官の推薦書#k を持って行け。");
    if (!player.haveItem(4032375)) {
        player.gainItem(4032375, 1);
    }
    player.startQuest(2302);
    if (knows) {
        player.warp(106020000, 0);
        return;
    }
    qm.sendOk("よし、道順を教えよう。#bヘネシスの西の入口#k の近くに #b空き家#k がある。中に入って左へ進むと #b<テーマダンジョン：キノコ城>#k に着く。そこがキノコ王国の入口だ。時間がないぞ！");
}

function end() {
    if (!player.haveItem(4032375)) {
        qm.sendNext("何の用だ、ん？");
        return;
    }
    qm.sendNext("ん？　それは #b転職官の推薦書#k か？！　なるほど、我々の窮状を聞いて駆けつけてくれたのだな。");
    qm.sendNext("よし…転職官の推薦があるなら、お前の腕は信じよう。だがその前に、我が国の #b勇者の試験#k を受けてもらう。");
    player.gainItem(4032375, -1);
    player.gainExp(6000);
    player.completeQuest(2302);
    player.startQuest(2312);
}
