// ストライカーの道 (quest 20105, NPC 1101007 ホークアイ) — ノーブレス(1000)の 1次転職。決断を確かめてから 初期装備(1482014 初心者海賊のナックル)を渡し、
// 転職(1500)・ステータス初期化・完了。勲章 見習い騎士の勲章(1142066) は JMS では 29906 の称号クエストが渡すのでここでは渡さない
// (Cosmic は渡す)。出典 Reference/Cosmic/scripts/quest/20105.js。JMS: 終了スクリプト q20105e、Check は 20100 完了・Lv10・職業 1000、Act は空。台詞は創作。
function end() {
    if (!qm.askYesNo("決心はついたか？　一度決めたら、もう取り消しはできない。#rストライカー#k の道を歩む覚悟はあるか？")) {
        qm.sendOk("大事な決断だ。よく考えてから、また来なさい。");
        return;
    }
    if (player.getJob() != 1000) {
        qm.sendOk("そなたはもう騎士の道を歩んでいるではないか。");
        return;
    }
    if (player.getLevel() < 10) {
        qm.sendOk("#bレベル 10#k になるまで、もう少し修行を積みなさい。それから #rストライカー#k の道を示そう。");
        return;
    }
    player.gainItem(1482014, 1);
    player.changeJob(1500);
    player.resetStatsForJob();
    player.completeQuest(20105);
    qm.sendNext("そなたの体を、ストライカーにふさわしいものに作り替えた。ステータスは職に合わせて初期化し、残りはすべて AP として戻してある。");
    qm.sendNext("装備の欄も広げておいた。それと、渡した初期装備を身に着けなさい。これからの修行の相棒だ。");
    qm.sendNext("#bSP#k も少し渡してある。#bスキルウィンドウ#k を開いて、ストライカーのスキルに振り分けてみなさい。");
    qm.sendNext("ノーブレスの頃と違い、ストライカーになってからはレベルが上がるたびに SP が 3 ずつ入る。無駄なく使うのだ。");
    qm.sendOk("さあ行け。ストライカーがどれほどのものか、世界に示してくるがいい。");
}
