// ヒューズの科学の授業 (quest 6031, 受注 2110004 マレン → 完了 NPC 2012017 ヒューズ) — 科学理論の基礎講義を聞いて受講料 10,000 メソを払う。
// 受講料は JMS の Act[1](money -10000)がデータ経路で引く。出典 Reference/Cosmic/scripts/quest/6031.js。JMS: 終了スクリプト q6031e。
// 台詞は創作(講義の趣旨は Cosmic どおり)。
function end() {
    if (player.getMeso() < 10000) {
        qm.sendOk("授業を受けるなら、まず受講料の #b10,000 メソ#k を用意してきてください。");
        return;
    }
    qm.sendNext("では、科学理論の基礎を教えましょう。");
    qm.sendNext("錬金術が要求を満たせないところで、科学が舞台に立ちます。観察し、測り、再現できる手順に落とし込む。それが科学です。");
    qm.sendNext("#bメイカー#k でも同じことです。どの材料をどれだけ使えば何ができるか、手順が決まっているから何度でも同じ物が作れる。");
    qm.sendNext("忘れないでください。科学の視点とは「なぜそうなるのか」を問い続けることです。");
    qm.sendOk("これで基礎はお分かりですね？　では授業はここまで。受講料はいただきます。");
    player.completeQuest(6031);
}
