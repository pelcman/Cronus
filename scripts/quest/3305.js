// ジェニミストのマントを再び受け取る。 (quest 3305, NPC 2111000 カソン) — 失くしたジェニミストのマント(1102135)を作り直してもらう。
// 材料(エメラルド 4021003×5、動物の皮 4000021×10)と 10,000 メソは JMS の Check[1]/Act[1] がデータ経路で処理するので、開始スクリプトは
// 説明して受注するだけ。3 日(interval 4320 分)に 1 回。出典 Reference/Cosmic/scripts/quest/3305.js。JMS: 開始スクリプト q3305s。台詞は創作。
function start() {
    qm.sendNext("#bジェニミストのマント#k を失くしたのか。もう一度作ってやってもいいが、材料が要る。");
    if (!qm.askAccept("新しいマントを作るには #b#t4021003# 5 個#k、#b#t4000021# 10 枚#k、それに #b10,000 メソ#k が必要だ。用意できるか？")) {
        qm.sendOk("そうか。材料がそろったら、また来るといい。");
        return;
    }
    qm.sendOk("材料が全部そろったら、また声をかけてくれ。");
    player.startQuest(3305);
}
