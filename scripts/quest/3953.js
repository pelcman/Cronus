// ムハマードを説得する。 (quest 3953, NPC 2100001 ムハマード, アリアント) — リチウム(4011008)を持って話すとデオの話を聞いて完了。
// 報酬 EXP 20000 は Cosmic の値(JMS の Act は空)。出典 Reference/Cosmic/scripts/quest/3953.js。JMS: 終了スクリプト q3953e、Check は 4011008×1。台詞は創作。
function end() {
    if (!player.haveItem(4011008)) {
        qm.sendOk("#b#t4011008##k を持ってきてくれれば、話を聞いてやろう。");
        return;
    }
    qm.sendNext("まだデオを怪物だと言うのか？　違う。デオは怪物じゃない、砂漠の穏やかな主だ。人を襲うのは、縄張りを荒らされたときだけさ。");
    qm.sendNext("そうか…どうして商人たちが、あんな無防備に砂漠をうろついていたんだろうな。まるで何かに追われていたみたいだ。");
    qm.sendNext("ああ…この町が今の政（まつりごと）のせいでうまくいっていないのは確かだ。王妃は税を搾り取るばかりで、民のことなど考えちゃいない。");
    qm.sendNext("兵たちは砂漠の脅威を取り除くために遠征に出ている。町を守る者がいない今、何が起きてもおかしくない…。");
    player.gainItem(4011008, -1);
    player.gainExp(20000);
    player.completeQuest(3953);
    qm.sendOk("もし本当にそうなら、俺たちは大変なことになる。もし王宮のサボテンが…いや、今はこれ以上言うまい。気をつけて行けよ。");
}
