// 最高の武器を探して (quest 21202, NPC 1203000 仙人翁, Lv30) — 最高の鉾を求めて仙人翁を訪ね、資格の印(4032311)を 30 個集めて鉾マッハを打ってもらう。
// 出典 Reference/Cosmic/scripts/quest/21202.js。JMS: 開始 q21202s / 終了 q21202e、Check は 21201 進行中(+隠し記録 21203 = "0")、完了は 4032311×30、
// Act は空(印の回収はスクリプト側)。台詞は創作。
function start() {
    qm.sendNext("ほう…こんな人里離れた所に、若いのが何の用だ？");
    qm.sendNext("（最高の鉾を手に入れに来た！）");
    qm.sendNext("最高の鉾だと？　そんな物は、どこかの店で買えばよかろう。");
    qm.sendNext("（あなたはメイプルワールド一の鍛冶屋だと聞いた。あなたに打ってもらいたいんだ！）");
    if (!qm.askAccept("わしはもう年で、武器を打つ気はない。だが…昔打った鉾が一本ある。お前にふさわしいか、試してやろう。資格を示す印を持ってくるのだ。受けるか？")) {
        qm.sendOk("最高の武器のためなら、それくらいの手間はかけるものだと思うがな。");
        return;
    }
    qm.sendOk("そうか、そこまで言うなら断れまい。#b#t4032311##k を 30 個集めてこい。話はそれからだ。");
    player.startQuest(21202);
}

function end() {
    if (player.itemQuantity(4032311) < 30) {
        qm.sendOk("#b#t4032311##k を 30 個だ。");
        return;
    }
    qm.sendNext("おお、#t4032311# を持ってきたか。見かけより強いのう。");
    qm.sendNext("（長い時間が経ち、#p1203000# は鉾を手渡してくれた。）");
    if (!qm.askYesNo("ほれ、これがお前の求めていた鉾、#p1201002# だ。大切に扱えよ。受け取るか？")) {
        qm.sendOk("ん？　ここまで来て、まだ迷うのか？　まあいい、いつでも取りに来い。");
        return;
    }
    player.gainItem(4032311, -30);
    player.completeQuest(21202);
}
