// ウィンドブレイカーの道 (quest 20103, NPC 1101005 イリーナ) — ノーブレス(1000)の 1次転職。決断を確かめてから 初期装備(1452051 初歩弓使いの弓 + 矢 2060000×2000)を渡し、
// 転職(1300)・ステータス初期化・完了。勲章 見習い騎士の勲章(1142066) は JMS では 29906 の称号クエストが渡すのでここでは渡さない
// (Cosmic は渡す)。出典 Reference/Cosmic/scripts/quest/20103.js。JMS: 終了スクリプト q20103e、Check は 20100 完了・Lv10・職業 1000、Act は空。台詞は創作。
function end() {
    if (!qm.askYesNo("決心はついたか？　一度決めたら、もう取り消しはできない。#rウィンドブレイカー#k の道を歩む覚悟はあるか？")) {
        qm.sendOk("大事な決断だ。よく考えてから、また来なさい。");
        return;
    }
    if (player.getJob() != 1000) {
        qm.sendOk("そなたはもう騎士の道を歩んでいるではないか。");
        return;
    }
    if (player.getLevel() < 10) {
        qm.sendOk("#bレベル 10#k になるまで、もう少し修行を積みなさい。それから #rウィンドブレイカー#k の道を示そう。");
        return;
    }
    player.gainItem(1452051, 1);
    player.gainItem(2060000, 2000);
    player.changeJob(1300);
    player.resetStatsForJob();
    player.completeQuest(20103);
    qm.sendNext("そなたの体を、ウィンドブレイカーにふさわしいものに作り替えた。ステータスは職に合わせて初期化し、残りはすべて AP として戻してある。");
    qm.sendNext("装備の欄も広げておいた。それと、渡した初期装備を身に着けなさい。これからの修行の相棒だ。");
    qm.sendNext("#bSP#k も少し渡してある。#bスキルウィンドウ#k を開いて、ウィンドブレイカーのスキルに振り分けてみなさい。");
    qm.sendNext("ノーブレスの頃と違い、ウィンドブレイカーになってからはレベルが上がるたびに SP が 3 ずつ入る。無駄なく使うのだ。");
    qm.sendOk("さあ行け。ウィンドブレイカーがどれほどのものか、世界に示してくるがいい。");
}
