// ジェニミスト協会長のテスト (quest 3301, NPC 2111007 ブローカーハン) — 協会に入るための「テスト」をブローカーが金で片付ける。JMS の Check[1] に
// 残っている会話文(韓国語のまま)は「30000 メソくれればジェニミストに入れてやる」なので、Cosmic 版(GMS: 宝石の原石 2 個)ではなく
// JMS どおりメソを受け取る。JMS: 終了スクリプト q3301e、Act は空(支払いはスクリプト側)。台詞は創作。
function end() {
    if (player.getMeso() < 30000) {
        qm.sendOk("おっと、金が足りないじゃないか。#r30000 メソ#k 用意してから来な。話はそれからだ。");
        return;
    }
    if (!qm.askYesNo("客の望みなら何でも叶えてやるさ。もちろん、メソをくれるならな…。#r30000 メソ#k で #bジェニミスト#k に入れるように手を回してやる。どうだ、やるか？")) {
        qm.sendOk("そうかい。気が変わったらまた来な。この #m261000000# でお前を助けられるのは、この #p2111007# だけだぜ。");
        return;
    }
    player.gainMeso(-30000);
    qm.sendNext("よし、商談成立だ。しばらく待ってな。協会長を納得させる「研究成果」を用意してやる…。");
    player.completeQuest(3301);
}
