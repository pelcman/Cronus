function start() {
    qm.sendNext("何の用だい？　招かれざる客は歓迎しないんだが…いいさ、話を聞こう。");
    qm.sendNext("（巨大ネペンデスのことを話す。）");
    qm.sendNext("巨大ネペンデス？　確かに大きな問題だが、それがどうして私のところへ？");
    qm.sendNext("（放置された散歩道、と告げる。）");
    qm.sendNext("…放置された散歩道か。巨大ネペンデスがそこにいるなら、封印の庭園に関わっているのかもしれない。");
    qm.sendNext("（封印の庭園？）");
    if (!qm.askAccept("封印の庭園のことは、簡単には話せない。知りたければ、まずお前の運命を見せてもらう。いいかい？")) {
        return;
    }
    qm.sendOk("では、お前の運命を占おう。少し待ちな。");
    player.startQuest(21738);
}
