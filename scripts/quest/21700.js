// Cosmic は 1442000(ポールアーム)を渡すが、JMS の完了条件は 1442077 練習用鉾 なのでそちらを渡す。出典 Reference/Cosmic/scripts/quest/21700.js。
// JMS: 開始スクリプト q21700s、Check は Lv10、完了は 1442077×1(データ経路)。台詞は創作。
function start() {
    qm.sendNext("少しずつ思い出してきたようですね。鉾を握った感覚は、体が覚えているはずです。");
    qm.sendNext("（いくつかの技を覚えていると伝える。）");
    qm.sendNext("多くはありませんが、前進です。では次は、失った力をどう取り戻すか、ですね。");
    qm.sendNext("（どうすれば能力を取り戻せる？）");
    if (!qm.askAccept("方法は一つ。修行、修行、また修行です！　修練所で、教官のプオに鍛えてもらってください。いいですね？")) {
        qm.sendOk("え？　一人で鍛えられると？　…まあ、それも英雄らしいですが、教官の教えは無駄になりませんよ。");
        return;
    }
    if (!player.haveItem(1442077)) {
        player.gainItem(1442077, 1);
    }
    player.startQuest(21700);
    qm.sendNext("#b練習用の鉾#k を渡しておきます。あなたの記憶にある武器と、いちばん近いはずです。");
    qm.sendOk("修練所は、町を #b左#k に出た先です。教官の #p1202006# に、この鉾を見せてください。");
}
